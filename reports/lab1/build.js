const {
  Paragraph, TextRun, Math: OMath, MathRun, MathFraction, MathSum, MathRadical,
  MathSubScript, MathSuperScript, MathRoundBrackets, MathFunction,
} = require(require.resolve("docx", { paths: [path.join(lib, "lib")] }));

// абзац с нижними и верхними индексами: строка — обычный текст, { sub } / { sup } — индекс
const pi = (...parts) => new Paragraph({
  style: "OsnTekst",
  children: parts.map((s) => s instanceof OMath ? s
    : typeof s === "string" ? new TextRun(s)
    : new TextRun({ text: s.sub ?? s.sup, subScript: !!s.sub, superScript: !!s.sup })),
});
const i = { sub: "i" };

// формула Word (OMML) внутри абзаца
const r = (t) => new MathRun(t);
const all = (xs) => xs.map((x) => (typeof x === "string" ? r(x) : x));
const sub = (base, s) => new MathSubScript({ children: all([base]), subScript: all([s]) });
const sup = (base, s) => new MathSuperScript({ children: all([base]), superScript: all([s]) });
const frac = (num, den) => new MathFraction({ numerator: all(num), denominator: all(den) });
const sum = (...xs) => new MathSum({ children: all(xs), subScript: all(["i=1"]), superScript: all(["m"]) });
const root = (...xs) => new MathRadical({ children: all(xs) });
const br = (...xs) => new MathRoundBrackets({ children: all(xs) });
const fn = (name, ...xs) => new MathFunction({ name: all([name]), children: all(xs) });
const eq = (...xs) => new OMath({ children: all(xs) });

const xi = () => sub("x", "i");
const yi = () => sub("y", "i");
const err = () => br("f", br(xi()), "−", yi());   // (f(xᵢ) − yᵢ)

const src = (name) => fs.readFileSync(
  path.join(__dirname, "../../src/main/java/org/example/lab1", name), "utf8");

